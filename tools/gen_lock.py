#!/usr/bin/env python3
"""Generate a hash-pinned requirements lock file.

Resolves the given requirements with pip's own resolver (``pip install
--dry-run --report``), then queries the PyPI JSON API for the sha256 hash of
every distribution file of each resolved (name, version) pair.  The resulting
lock file can be installed with::

    pip install --require-hashes -r <lockfile>

All published file hashes are included per pin so the same lock works across
platforms and Python versions that resolve to the same version set.

Usage:
    python tools/gen_lock.py -o requirements/ci.lock pytest pytest-cov ruff numpy
    python tools/gen_lock.py -o requirements/runtime.lock -r requirements/runtime.txt

No third-party dependencies; requires network access to pypi.org.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

PYPI_JSON = "https://pypi.org/pypi/{name}/{version}/json"


def resolve(requirements: list[str]) -> list[tuple[str, str]]:
    """Resolve requirements to a flat list of (name, version) with pip."""
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
        report_path = tmp.name
    cmd = [
        sys.executable,
        "-m",
        "pip",
        "install",
        "--dry-run",
        "--quiet",
        "--report",
        report_path,
        *requirements,
    ]
    subprocess.run(cmd, check=True)  # noqa: S603 - argv built from our own CLI input
    report = json.loads(Path(report_path).read_text())
    pins = []
    for item in report["install"]:
        meta = item["metadata"]
        pins.append((meta["name"], meta["version"]))
    return sorted(pins, key=lambda p: p[0].lower())


def file_hashes(name: str, version: str) -> list[str]:
    """Fetch sha256 hashes for every published file of a release."""
    url = PYPI_JSON.format(name=name, version=version)
    with urllib.request.urlopen(url, timeout=30) as resp:  # noqa: S310 - fixed https URL
        data = json.load(resp)
    hashes = []
    for f in data["urls"]:
        digest = f.get("digests", {}).get("sha256")
        if not digest:
            raise RuntimeError(f"missing sha256 for {name}=={version} file {f['filename']}")
        if f.get("yanked"):
            continue
        hashes.append(digest)
    if not hashes:
        raise RuntimeError(f"no distribution files for {name}=={version}")
    return hashes


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("specs", nargs="*", help="requirement specifiers")
    ap.add_argument("-r", "--requirement", action="append", default=[], help="requirements file")
    ap.add_argument("-o", "--output", required=True, help="lock file to write")
    args = ap.parse_args()

    requirements = list(args.specs)
    for req_file in args.requirement:
        requirements += ["-r", req_file]
    if not requirements:
        ap.error("no requirements given")

    pins = resolve(requirements)
    lines = [
        "# Generated by tools/gen_lock.py -- do not edit by hand.",
        f"# Input: {' '.join(requirements)}",
        f"# Python: {sys.version.split()[0]}",
        "# Install with: pip install --require-hashes -r <this file>",
        "",
    ]
    for name, version in pins:
        hashes = file_hashes(name, version)
        print(f"{name}=={version}  ({len(hashes)} files)", file=sys.stderr)
        lines.append(f"{name}=={version} \\")
        for i, digest in enumerate(hashes):
            cont = "" if i == len(hashes) - 1 else " \\"
            lines.append(f"    --hash=sha256:{digest}{cont}")
    Path(args.output).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output} ({len(pins)} pins)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
