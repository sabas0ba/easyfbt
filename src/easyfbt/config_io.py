"""Config serialisation: Config -> dict -> TOML, and atomic persistence.

The stdlib ships a TOML reader (:mod:`tomllib`) but no writer, so a minimal
writer for the value types our config uses (str/int/float/bool and flat
lists thereof) lives here instead of pulling in a dependency.

``config_to_dict`` produces exactly the shape ``parse_config`` consumes, so
``parse_config(config_to_dict(cfg))`` round-trips -- the browser control
panel exchanges this dict over HTTP and the TOML file is generated from it.
"""

from __future__ import annotations

import tempfile
from dataclasses import fields
from pathlib import Path

from easyfbt.config import Config

_HEADER = "# easyfbt configuration (generated by the easyfbt settings UI).\n"


def _value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int | float):
        return repr(v)
    if isinstance(v, str):
        escaped = v.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    if isinstance(v, list | tuple):
        return "[" + ", ".join(_value(x) for x in v) + "]"
    raise TypeError(f"cannot serialise {type(v)!r} to TOML")


def _section(data: dict) -> list[str]:
    return [f"{key} = {_value(val)}" for key, val in data.items()]


def config_to_dict(cfg: Config) -> dict:
    """Config -> plain dict in the same shape parse_config() accepts."""

    def dc_dict(obj) -> dict:
        out = {}
        for f in fields(obj):
            v = getattr(obj, f.name)
            if isinstance(v, tuple):
                v = list(v)
            out[f.name] = v
        return out

    return {
        "tracking": {
            **{k: v for k, v in dc_dict(cfg.tracking).items() if k != "roles"},
            "roles": [r.value for r in cfg.tracking.roles],
        },
        "camera": [dc_dict(c) for c in cfg.cameras],
        "models": dc_dict(cfg.models),
        "output": {
            "vmt": dc_dict(cfg.vmt),
            "vrchat": dc_dict(cfg.vrchat),
            "vrcft": dc_dict(cfg.vrcft),
            "udp_json": dc_dict(cfg.udp_json),
        },
        "debug": dc_dict(cfg.debug),
    }


def dump_toml(cfg: Config) -> str:
    """Serialise a Config to a TOML document."""
    data = config_to_dict(cfg)
    lines: list[str] = [_HEADER]

    lines.append("[tracking]")
    lines += _section(data["tracking"])
    for cam in data["camera"]:
        lines.append("")
        lines.append("[[camera]]")
        lines += _section(cam)
    lines.append("")
    lines.append("[models]")
    lines += _section(data["models"])
    for name in ("vmt", "vrchat", "vrcft", "udp_json"):
        lines.append("")
        lines.append(f"[output.{name}]")
        lines += _section(data["output"][name])
    lines.append("")
    lines.append("[debug]")
    lines += _section(data["debug"])
    return "\n".join(lines) + "\n"


def save_config(cfg: Config, path: str | Path) -> None:
    """Atomically write the config as TOML."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        "w", dir=path.parent, suffix=".tmp", delete=False, encoding="utf-8"
    ) as tmp:
        tmp.write(dump_toml(cfg))
    Path(tmp.name).replace(path)
